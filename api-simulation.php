<?php
declare(strict_types=1);

/**
 * api-simulation.php — Server-Side Physics Calculations
**/

require_once 'config.php';
require_once 'simulation-engine.php';

header('Content-Type: application/json');
header('Cache-Control: no-store, no-cache, must-revalidate');

// SECURITY: Do NOT use Access-Control-Allow-Origin: * on authenticated endpoints.
// This endpoint requires a valid session + access token, so restrict CORS to
// same origin only. Preflight OPTIONS requests from other origins will be denied.
// If you need cross-origin access in future, explicitly list allowed origins.

// Handle preflight — only allow same-origin preflight
if ($_SERVER['REQUEST_METHOD'] === 'OPTIONS') {
    http_response_code(204);
    exit;
}

if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    jsonResponse(['error' => 'Method not allowed'], 405);
}

// Wrap everything in try/catch so auth failures return JSON not blank 500
try {
    $input = file_get_contents('php://input');
    $data  = json_decode($input, true);

    if (!$data) {
        jsonResponse(['error' => 'Invalid JSON'], 400);
    }

    $simulationType = $data['type']   ?? '';
    $params         = $data['params'] ?? [];
    $token          = $data['token']  ?? '';

    if (!$simulationType || !is_array($params)) {
        jsonResponse(['error' => 'Invalid request parameters'], 400);
    }

    // Authentication — requires active session
    $user = getCurrentUser();
    if (!$user) {
        jsonResponse(['error' => 'Authentication required'], 401);
    }

    // Token validation — token must be generated by generateAccessToken() in config.php
    $productId = 'sim-' . $simulationType;
    if (!validateAccessToken($token, (int)$user['id'], $productId)) {
        jsonResponse(['error' => 'Invalid or expired token'], 401);
    }

    // Purchase verification with 5-minute file cache to reduce DB load
    $cacheKey  = 'purchase_' . $user['id'] . '_' . $productId;
    $cacheFile = sys_get_temp_dir() . '/' . md5($cacheKey);
    $hasPurchase = false;

    if (file_exists($cacheFile) && (time() - filemtime($cacheFile)) < 300) {
        $hasPurchase = (bool)file_get_contents($cacheFile);
    } else {
        $db   = getDB();
        $stmt = $db->prepare("
            SELECT id FROM purchases
            WHERE user_id = ? AND product_id = ? AND status IN ('paid', 'demo')
            LIMIT 1
        ");
        $stmt->execute([$user['id'], $productId]);
        $hasPurchase = (bool)$stmt->fetch();
        file_put_contents($cacheFile, $hasPurchase ? '1' : '0');
    }

    if (!$hasPurchase) {
        jsonResponse(['error' => 'Purchase required'], 403);
    }

    // Rate limiting - 100 requests per minute per user (temp-file based)
    $rateLimitKey  = 'sim_rate_' . $user['id'];
    $rateLimitFile = sys_get_temp_dir() . '/' . md5($rateLimitKey);
    $requests  = 1;
    $resetTime = time() + 60;

    if (file_exists($rateLimitFile)) {
        $rateData = json_decode((string)file_get_contents($rateLimitFile), true);
        if ($rateData && time() < (int)($rateData['reset'] ?? 0)) {
            $requests  = (int)($rateData['count'] ?? 0) + 1;
            $resetTime = (int)$rateData['reset'];
            if ($requests > 100) {
                jsonResponse([
                    'error'       => 'Rate limit exceeded',
                    'retry_after' => $resetTime - time(),
                ], 429);
            }
        }
    }

    file_put_contents($rateLimitFile, json_encode(['count' => $requests, 'reset' => $resetTime]));

    // Run calculation
    $startTime = microtime(true);
    $result    = SimulationEngine::calculate($simulationType, $params);
    $calcTime  = round((microtime(true) - $startTime) * 1000, 2);

    jsonResponse([
        'success' => true,
        'data'    => $result,
        'meta'    => [
            'calc_time_ms' => $calcTime,
            'server_time'  => time(),
            'watermarks'   => [
                'code_author' => 'Pancham Kotian',
                'owner'       => 'Akilesh Bhandary',
                'ai_generated'=> 'Claude (Anthropic)',
            ],
        ],
    ]);

} catch (PDOException $e) {
    error_log('Simulation DB error: ' . $e->getMessage());
    jsonResponse(['error' => 'Database error'], 500);
} catch (Exception $e) {
    error_log('Simulation error: ' . $e->getMessage());
    jsonResponse([
        'error'   => 'Calculation failed',
        'message' => DEMO_MODE ? $e->getMessage() : 'Internal error',
    ], 500);
}
